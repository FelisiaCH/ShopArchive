// The server serves it under a CSP of `style-src 'self'`: styles live in styles.css, never in Compose HTML's StyleSheet / Style().
kotlin {
    js {
        browser {
            commonWebpackConfig { outputFileName = "webapp.js" }
        }
        binaries.executable()
    }

    sourceSets {
        named("jsMain").configure {
            dependencies {
                implementation(project(":clientCore"))
                implementation(libs.compose.runtime)
                implementation(libs.compose.html.core)
            }
            kotlin.srcDir(generateWebStrings.flatMap { it.outputDir })
        }
    }
}
