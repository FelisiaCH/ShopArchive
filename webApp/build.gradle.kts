// th / lo / en strings of composeApp as Kotlin maps (plain <string> only; plurals are left out). Format args (%1$s) stay as they are.
abstract class GenerateWebStrings : DefaultTask() {
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val en: RegularFileProperty
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val th: RegularFileProperty
    @get:InputFile @get:PathSensitive(PathSensitivity.NONE) abstract val lo: RegularFileProperty
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    // Android string resource rules: a "quoted" value keeps its spaces, otherwise whitespace collapses; then backslash escapes.
    private fun unescape(raw: String): String {
        val quoted = raw.length >= 2 && raw.startsWith('"') && raw.endsWith('"')
        val text = if (quoted) raw.substring(1, raw.length - 1) else raw.trim().replace(Regex("\\s+"), " ")
        val out = StringBuilder()
        var i = 0
        while (i < text.length) {
            val c = text[i]
            if (c != '\\' || i + 1 == text.length) { out.append(c); i++; continue }
            when (val n = text[i + 1]) {
                'n' -> { out.append('\n'); i += 2 }
                't' -> { out.append('\t'); i += 2 }
                'u' -> { out.append(text.substring(i + 2, i + 6).toInt(16).toChar()); i += 6 }
                else -> { out.append(n); i += 2 } // \' \" \\ \@ \?
            }
        }
        return out.toString()
    }

    private fun entries(file: java.io.File): List<Pair<String, String>> {
        val nodes = javax.xml.parsers.DocumentBuilderFactory.newInstance().newDocumentBuilder().parse(file).documentElement.childNodes
        return (0 until nodes.length).map { nodes.item(it) }
            .filterIsInstance<org.w3c.dom.Element>()
            .filter { it.tagName == "string" }
            .map { it.getAttribute("name") to unescape(it.textContent) }
    }

    private fun literal(s: String) =
        "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$").replace("\n", "\\n").replace("\t", "\\t") + "\""

    @TaskAction
    fun generate() {
        val source = StringBuilder("package xyz.felismp.shoparchive.web\n\n// Generated by :webApp:generateWebStrings from composeApp's strings.xml. Do not edit.\nobject WebStrings {\n")
        for ((lang, file) in listOf("en" to en, "th" to th, "lo" to lo)) {
            source.append("    val $lang: Map<String, String> = mapOf(\n")
            entries(file.get().asFile).forEach { (k, v) -> source.append("        ${literal(k)} to ${literal(v)},\n") }
            source.append("    )\n")
        }
        source.append("}\n")
        val dir = outputDir.get().asFile.resolve("xyz/felismp/shoparchive/web")
        dir.mkdirs()
        dir.resolve("WebStrings.kt").writeText(source.toString())
    }
}

val generateWebStrings = tasks.register<GenerateWebStrings>("generateWebStrings") {
    val res = rootProject.layout.projectDirectory.dir("composeApp/src/commonMain/composeResources")
    en.set(res.file("values/strings.xml"))
    th.set(res.file("values-th/strings.xml"))
    lo.set(res.file("values-lo/strings.xml"))
    outputDir.set(layout.buildDirectory.dir("generated/webStrings"))
}

